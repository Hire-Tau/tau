/** Total size of the name pool — exposed for callers/tests reasoning about exhaustion. */
export const AGENT_NAME_POOL_SIZE = NAMES.length

/** Pick a random element from an array. */
function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)]
}

/**
 * Generate a random single-word agent name.
 *
 * Pass `taken` (names already used in the addressing scope, e.g. a squad) to get a name not in that
 * set — so agents are uniquely identifiable by name within their squad. Only once every pool name is
 * taken do we fall back to reuse (names stay disambiguated by purpose + id at that point).
 */
export function generateAgentName(taken?: Iterable<string>): string {
  if (taken) {
    const used = new Set(taken)
    const available = NAMES.filter((name) => !used.has(name))
    if (available.length > 0) return pick(available)
    // Pool exhausted for this scope — reuse a name rather than fail.
  }
  return pick(NAMES)
}
